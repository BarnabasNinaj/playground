function withPlaceTags(items) {
  return items.map((item) => {
    const tags = new Set(item.tags || [])
    if (tags.has('car') || tags.has('outdoors')) tags.delete('indoor')
    else tags.add('indoor')
    return { ...item, tags: [...tags] }
  })
}

