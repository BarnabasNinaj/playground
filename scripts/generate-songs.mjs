function esc(s) {
  return s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')
}

function toEntry(song, lang) {
  const L = lang === 'SK' ? 'SK' : 'CZ'
  const stages = range(song.from, song.to)
  return `  {
    id: '${song.id}',
    type: 'song',
    category: 'songs',
    stages: ${JSON.stringify(stages)},
    tags: ${JSON.stringify(song.tags)},
    title: '${song[`title${L}`].replace(/'/g, "\\'")}',
    description: '${song[`desc${L}`].replace(/'/g, "\\'")}',
    materials: [],
    steps: [],
    lyrics: \`${esc(song[`lyrics${L}`])}\`,
    actions: '${song[`actions${L}`].replace(/'/g, "\\'")}',
    notes: '${song[`notes${L}`].replace(/'/g, "\\'")}',
    duration: '2–4 min',
  }`
}

function buildFile(lang) {
  const body = songs.map((s) => toEntry(s, lang)).join(',\n')
  return `/** Extra traditional SK/CZ children's songs */\nexport const songsExtra${lang} = [\n${body},\n]\n`
}

