function esc(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')
}

function arr(a) {
  return `[${a.map((x) => `'${String(x).replace(/'/g, "\\'")}'`).join(', ')}]`
}

function toEntry(item, lang) {
  const L = lang === 'SK' ? 'SK' : 'CZ'
  const stages = range(item.from, item.to)
  const placeTag = item.place === 'outdoors' ? 'outdoors' : 'indoor'
  const tags = [...new Set([placeTag, ...item.tags.filter((t) => t !== 'indoor' && t !== 'outdoors')])]
  return `  {
    id: '${item.id}',
    type: 'activity',
    category: '${item.category}',
    stages: ${JSON.stringify(stages)},
    tags: ${JSON.stringify(tags)},
    title: '${item[`title${L}`].replace(/'/g, "\\'")}',
    description: '${item[`desc${L}`].replace(/'/g, "\\'")}',
    materials: ${arr(item[`materials${L}`])},
    steps: ${arr(item[`steps${L}`])},
    notes: '${item[`notes${L}`].replace(/'/g, "\\'")}',
    duration: '${item.duration}',
  }`
}

function build(lang) {
  return `/** Extra indoor/outdoor activities */\nexport const activitiesPlace${lang} = [\n${items.map((i) => toEntry(i, lang)).join(',\n')},\n]\n`
}

